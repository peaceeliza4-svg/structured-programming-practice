#include <stdio.h>
#include <stdlib.h>

int main()
{

    for (int j=30;j>=-30;j-=10)
    {
        printf("j=%d\n",j);
    }
    for (int i=15;i<=55;i+=8)
    {
        printf("i=%d\n",i);
    }
    for (int x=1;x<=13;x+=2)
    {
        printf("\nx=%d",x);
    }


    return 0;
}
